"""Inventory of a client codebase: files, languages, size hotspots and the detected tech stack.

Read-only and offline: walks the tree (never follows symlinks out of the root), skips vendored and
generated folders, and never executes anything from the codebase.
"""
from __future__ import annotations

import json
import re
import subprocess
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional

SKIP_DIRS = {
    ".git", "node_modules", "vendor", "dist", "build", "out", ".next", ".nuxt", "coverage", "__pycache__",
    ".venv", "venv", "env", ".tox", ".mypy_cache", ".pytest_cache", "target", "bin", "obj", ".gradle",
    ".dart_tool", ".idea", ".vscode", "bower_components", ".cache", "tmp", "logs", "storage",
}
LANGUAGES = {
    ".py": "Python", ".js": "JavaScript", ".jsx": "JavaScript", ".mjs": "JavaScript", ".cjs": "JavaScript",
    ".ts": "TypeScript", ".tsx": "TypeScript", ".php": "PHP", ".rb": "Ruby", ".go": "Go", ".java": "Java",
    ".kt": "Kotlin", ".swift": "Swift", ".dart": "Dart", ".cs": "C#", ".cpp": "C++", ".c": "C", ".rs": "Rust",
    ".vue": "Vue", ".svelte": "Svelte", ".html": "HTML", ".css": "CSS", ".scss": "CSS", ".sql": "SQL",
    ".sh": "Shell",
}
GENERATED_DIRS = {"generated", "__generated__", "gen", "migrations_generated"}
GENERATED_MARKER = re.compile(r"@generated|DO NOT EDIT|auto-?generated|Code generated by", re.IGNORECASE)
MAX_FILE_BYTES = 2_000_000  # larger files are counted but not read (likely data or bundles)
LARGE_FILE_LINES = 500


@dataclass
class SourceFile:
    path: str
    language: str
    lines: int


@dataclass
class Inventory:
    root: Path
    files: List[SourceFile] = field(default_factory=list)
    all_paths: List[str] = field(default_factory=list)
    skipped_large: List[str] = field(default_factory=list)
    generated: List[SourceFile] = field(default_factory=list)
    stack: Dict[str, List[str]] = field(default_factory=dict)
    source: str = "folder"

    @property
    def lines_by_language(self) -> Dict[str, int]:
        totals: Dict[str, int] = {}
        for item in self.files:
            totals[item.language] = totals.get(item.language, 0) + item.lines
        return dict(sorted(totals.items(), key=lambda kv: -kv[1]))

    def large_files(self, limit: int = 10) -> List[SourceFile]:
        big = [f for f in self.files if f.lines > LARGE_FILE_LINES]
        return sorted(big, key=lambda f: -f.lines)[:limit]

    def has(self, *names: str) -> bool:
        return any(name in self.all_paths for name in names)

    def read(self, rel: str) -> Optional[str]:
        path = self.root / rel
        try:
            if path.is_file() and path.stat().st_size <= MAX_FILE_BYTES:
                return path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            return None
        return None


def build_inventory(root: Path) -> Inventory:
    root = root.resolve()
    inv = Inventory(root=root)
    tracked = _git_tracked(root)
    inv.source = "git-tracked files" if tracked is not None else "folder"
    for path in (tracked if tracked is not None else _walk(root)):
        rel = path.relative_to(root).as_posix()
        inv.all_paths.append(rel)
        language = LANGUAGES.get(path.suffix.lower())
        if not language:
            continue
        try:
            size = path.stat().st_size
        except OSError:
            continue
        if size > MAX_FILE_BYTES or rel.endswith((".min.js", ".min.css")):
            inv.skipped_large.append(rel)
            continue
        try:
            with path.open("rb") as handle:
                lines = sum(1 for _ in handle)
        except OSError:
            continue
        item = SourceFile(rel, language, lines)
        (inv.generated if _is_generated(path, rel) else inv.files).append(item)
    inv.stack = detect_stack(inv)
    return inv


def _git_tracked(root: Path):
    """Files git tracks (what a client hands over), or None if this isn't a usable git checkout."""
    if not (root / ".git").exists():
        return None
    try:
        out = subprocess.run(["git", "-C", str(root), "ls-files", "-z"], capture_output=True, timeout=60)
    except (OSError, subprocess.SubprocessError):
        return None
    if out.returncode != 0:
        return None
    paths = []
    for rel in out.stdout.decode("utf-8", "replace").split("\0"):
        if not rel or any(part in SKIP_DIRS for part in Path(rel).parts[:-1]):
            continue
        path = root / rel
        if path.is_file() and not path.is_symlink():
            paths.append(path)
    return paths


def _is_generated(path: Path, rel: str) -> bool:
    parts = Path(rel).parts[:-1]
    if any(part in GENERATED_DIRS for part in parts):
        return True
    if "migrations" in parts and path.suffix == ".sql":
        return True  # written by the migration tool, not by hand
    try:
        with path.open("r", encoding="utf-8", errors="replace") as handle:
            head = "".join(handle.readline() for _ in range(5))
    except OSError:
        return False
    return bool(GENERATED_MARKER.search(head))


def _walk(root: Path):
    stack = [root]
    while stack:
        current = stack.pop()
        try:
            entries = sorted(current.iterdir())
        except OSError:
            continue
        for entry in entries:
            if entry.is_symlink():
                continue  # never follow links: they may point outside the client's code
            if entry.is_dir():
                if entry.name not in SKIP_DIRS:
                    stack.append(entry)
            elif entry.is_file():
                yield entry


def _json(inv: Inventory, rel: str) -> dict:
    try:
        return json.loads(inv.read(rel) or "{}")
    except ValueError:
        return {}


def detect_stack(inv: Inventory) -> Dict[str, List[str]]:
    """Languages, frameworks, package managers and databases, from files present (no execution)."""
    names = {Path(p).name for p in inv.all_paths}
    frameworks: List[str] = []
    managers: List[str] = []
    databases: List[str] = []

    pkg = _json(inv, "package.json")
    deps = {**pkg.get("dependencies", {}), **pkg.get("devDependencies", {})} if pkg else {}
    for dep, label in (("next", "Next.js"), ("react", "React"), ("vue", "Vue"), ("nuxt", "Nuxt"), ("svelte", "Svelte"),
                       ("@angular/core", "Angular"), ("express", "Express"), ("@nestjs/core", "NestJS"),
                       ("react-native", "React Native"), ("electron", "Electron"), ("@prisma/client", "Prisma"),
                       ("vite", "Vite"), ("tailwindcss", "Tailwind CSS")):
        if dep in deps:
            frameworks.append(label)
    for lock, label in (("pnpm-lock.yaml", "pnpm"), ("yarn.lock", "Yarn"), ("package-lock.json", "npm"), ("bun.lockb", "Bun")):
        if lock in names:
            managers.append(label)
    if pkg and not managers:
        managers.append("npm (no lockfile)")

    composer = _json(inv, "composer.json")
    if composer:
        managers.append("Composer")
        req = {**composer.get("require", {}), **composer.get("require-dev", {})}
        if "laravel/framework" in req:
            frameworks.append("Laravel")
        if any(k.startswith("symfony/") for k in req):
            frameworks.append("Symfony")
    if "wp-config.php" in names or any(p.startswith("wp-content/") or "/wp-content/" in p for p in inv.all_paths):
        frameworks.append("WordPress")

    py_req = " ".join(filter(None, (inv.read(p) for p in ("requirements.txt", "pyproject.toml", "Pipfile")))).lower()
    if py_req:
        managers.append("pip/poetry" if "pyproject.toml" in names else "pip")
        for dep, label in (("django", "Django"), ("flask", "Flask"), ("fastapi", "FastAPI"), ("sqlalchemy", "SQLAlchemy"),
                           ("celery", "Celery"), ("streamlit", "Streamlit")):
            if re.search(rf"\b{dep}\b", py_req):
                frameworks.append(label)

    for marker, label in (("pubspec.yaml", "Flutter/Dart"), ("go.mod", "Go modules"), ("Cargo.toml", "Cargo"),
                          ("pom.xml", "Maven"), ("build.gradle", "Gradle"), ("Gemfile", "Bundler"), ("Package.swift", "SwiftPM")):
        if marker in names:
            managers.append(label)
    if any(p.endswith(".csproj") for p in inv.all_paths):
        managers.append(".NET")

    text = " ".join(filter(None, (inv.read(p) for p in ("docker-compose.yml", "docker-compose.yaml", ".env.example",
                                                           "prisma/schema.prisma")))).lower()
    for word, label in (("postgres", "PostgreSQL"), ("mysql", "MySQL"), ("mariadb", "MariaDB"), ("mongo", "MongoDB"),
                        ("redis", "Redis"), ("sqlite", "SQLite")):
        if word in text or word in py_req or word in json.dumps(deps).lower():
            databases.append(label)

    languages = [lang for lang in inv.lines_by_language if lang not in {"HTML", "CSS", "Shell", "SQL"}][:4]
    return {"languages": languages, "frameworks": sorted(set(frameworks)), "package_managers": sorted(set(managers)),
            "databases": sorted(set(databases)), "containers": ["Docker"] if any(n in names for n in ("Dockerfile", "docker-compose.yml", "docker-compose.yaml")) else []}
